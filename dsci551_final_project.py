class CustomDataFrame:
    def __init__(self, data_dict):
        self.data = data_dict # dictionary keys are columns names, and values are a list of column data
        self.columns = list(data_dict.keys()) #list of column names
        self.num_rows = len(next(iter(data_dict.values()), [])) #number of rows

    def __getitem__(self, key):
        # Handle both df['col'] and df[['col1', 'col2']]
        if isinstance(key, list):
            # Projection: return new DataFrame with selected columns
            return CustomDataFrame({col: self.data[col] for col in key})
        else:
            # Single column access
            return self.data.get(key, [])

    def head(self, n=5): # returns first n rows of each columns
        return {col: vals[:n] for col, vals in self.data.items()}

    def print(self):
        for i in range(self.num_rows):
            row = {col: self.data[col][i] for col in self.columns}
            print(row)

"""#### Custom funtion to parse the csv"""

def parse_csv(file_path, separator=',', parse_dates=True, auto_detect_separator=False):
    try:
        with open(file_path, 'r') as f: #read file line by line
            lines = [line.strip() for line in f if line.strip()]
    except FileNotFoundError:
        raise ValueError(f"File not found: {file_path}")

    if not lines: # read empty csv file
        raise ValueError("CSV file is empty")

    # Auto-detect separator if needed
    if auto_detect_separator:
        for sep in [',', ';', '\t', '|']:
            if sep in lines[0]:
                separator = sep
                break

    header = lines[0].split(separator)
    num_columns = len(header)
    data_dict = {col: [] for col in header}
    warnings = []

    for line_num, line in enumerate(lines[1:], start=2):
        values = line.split(separator)

        if len(values) != num_columns: # check if value match header length
            warnings.append(f"Line {line_num}: Expected {num_columns} values, got {len(values)}. Skipping.")
            continue

        for i, value in enumerate(values):
            typed_value = infer_type(value, parse_dates=parse_dates)
            data_dict[header[i]].append(typed_value)

    if warnings:
        print("Parsing Warnings:")
        for w in warnings:
            print("  -", w)

    return CustomDataFrame(data_dict)

"""#### Infer Types : When you read a CSV file, everything(even numbers, booleans, and dates) starts as a string. But real-world data analysis needs proper types. infer_type() helps by: Converting Strings to Native Python Types

"""

def infer_type(value, parse_dates=True):
    value = value.strip()

    if value.lower() in ('', 'null', 'na', 'nan'):
        return None
    if value.lower() == 'true':
        return True
    if value.lower() == 'false':
        return False

    try:
        return int(value)
    except ValueError:
        pass

    try:
        return float(value)
    except ValueError:
        pass

    if parse_dates:
        for fmt in ("%Y-%m-%d", "%d/%m/%Y", "%m/%d/%Y"):
            try:
                return datetime.strptime(value, fmt)
            except ValueError:
                continue

    return value #fall back to string if no match

